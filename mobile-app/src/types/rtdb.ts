/**
 * Firebase Realtime Database Data Models for HyFePoul
 *
 * These models follow docs/database-schema.md (moving-hopper design).
 */
import { CycleStep, TimeSource } from './index';

/**
 * The core physical state of the Arduino/ESP32 hardware device.
 */
export interface RTDBDeviceState {
  feedWeightGrams: number;    // total of the 5 trays
  targetFeedGrams: number;    // per tray
  trayWeightsGrams: number[]; // trays 1-5 (indices 0-4)
  hopperLevelPercent: number;
  waterLow: boolean;          // reservoir float switch (no pump)
  feedingActive: boolean;
  cycleStep: CycleStep;
  currentTray: number;        // 0 = none
  emergencyStopActive: boolean;
  timeSource?: TimeSource;    // the Mega's clock source (R-44)
  timestamp: number; // UTC timestamp generated by device
}

/**
 * Represents the top-level device object in /devices/{deviceId}
 */
export interface RTDBDevice {
  ownerId: string | null;       // The human user Firebase Auth UID
  deviceAuthUid: string | null; // The ESP32's Firebase Auth UID
  status: 'online' | 'offline'; // Device connection status
  lastHeartbeat: number;        // UTC timestamp
  megaLinkOk?: boolean;         // ESP32: Mega heard within the last 30 s
  state?: RTDBDeviceState;      // Current state (optional if not yet reported)
}

/**
 * A historical snapshot of the device state stored in /systemData/{deviceId}/{pushId}
 */
// Same exact properties as RTDBDeviceState, representing a fixed point in time.
export type RTDBSystemDataSnapshot = RTDBDeviceState;

export type RTDBAlertType = 'LOW_FEED' | 'LOW_WATER' | 'CHAIN_TIMEOUT' | 'TRAY_TIMEOUT' | 'EMERGENCY_STOP' | 'CONTROLLER_OFFLINE' | 'DEVICE_OFFLINE';

/**
 * An actionable alert/event generated by the device, stored in /alerts/{deviceId}/{pushId}
 */
export interface RTDBAlert {
  eventId: string;
  name: RTDBAlertType;
  timestamp: number;
  resolved: boolean;  // set by the device when the condition clears
  resolvedAt?: number; // UTC ms, present while resolved
}

/**
 * Temporary claim request object used during the 2-step device claiming process
 * Stored in /claimRequests/{deviceId}
 */
export interface RTDBClaimRequest {
  uid: string; // The human user's Firebase Auth UID
  pin: string; // The plaintext setup PIN provided by the user
}

export type RTDBCommandStatus = 'queued' | 'acknowledged' | 'executing' | 'completed' | 'failed' | 'rejected';
export type RTDBCommandAction = 'MANUAL_FEED' | 'ESTOP_RELEASE' | 'SYSTEM_RESTART' | 'STATUS_REQ' | 'SCHEDULE_SET';

/**
 * What the Mega accepted for a schedule slot, written by the device (R-43).
 * Stored in /scheduleStatus/{deviceId}/{scheduleId}.
 */
export interface RTDBScheduleStatus {
  hour: number;
  minute: number;
  targetGrams: number;
  enabled: boolean;
  appliedAt: number;
}

/**
 * One day of totals counted by the Mega (R-22), local date (UTC+8).
 * Stored in /dailySummary/{deviceId}/{YYYY-MM-DD}; rewritten during the day.
 */
export interface RTDBDailySummary {
  date: string; // YYYY-MM-DD, same as the key
  feedGrams: number;
  cyclesCompleted: number;
  cyclesIncomplete: number;
  trayTimeouts: number;
  chainFaults: number;
  lowWaterAlerts: number;
  lowFeedAlerts: number;
  emergencyStops: number;
  updatedAt: number;
}

export interface RTDBSchedule {
  scheduleId: string;
  hour: number;
  minute: number;
  targetGrams: number;
  enabled: boolean;
  daysOfWeek: number[]; // Required by the RTDB schema; the app always writes all 7 days because the Mega runs schedules daily (decision D3)
}

/**
 * Remote command object, stored in /commands/{deviceId}/{commandId}
 */
export interface RTDBCommand {
  commandId: string;
  command: RTDBCommandAction;
  parameters?: Record<string, any>;
  issuedBy: string; // Owner UID
  createdAt: number;
  status: RTDBCommandStatus;
  acknowledgedAt?: number;
  completedAt?: number;
  error?: string;
}
